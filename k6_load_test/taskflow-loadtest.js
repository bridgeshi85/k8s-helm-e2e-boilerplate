import http from 'k6/http';
import { check, sleep } from 'k6';
import { randomString } from 'https://jslib.k6.io/k6-utils/1.2.0/index.js';

// 1. 测试配置 (Configuration)
export const options = {
    // 模拟真实的用户流量波浪
    stages: [
        { duration: '10s', target: 20 }, // 10秒内将虚拟用户(VU)提升到 20
        { duration: '30s', target: 20 }, // 在 20 个并发用户保持 30 秒 (压测观察期)
        { duration: '10s', target: 0 },  // 10秒内缓慢停止
    ],
    // 性能阈值 (Thresholds)
    thresholds: {
        http_req_failed: ['rate<0.01'],     // 错误率必须小于 1%
        http_req_duration: ['p(95)<500'],   // 95% 的请求延迟必须小于 500ms
    },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080/api';

function safeJsonPath(response, path) {
    if (!response || !response.body) {
        return undefined;
    }

    try {
        return response.json(path);
    } catch (_) {
        return undefined;
    }
}

function logFailure({ url, payload, params, res, checks }) {
    const failedChecks = Object.entries(checks)
        .filter(([, passed]) => !passed)
        .map(([name]) => name);

    console.error(
        `[k6][request-failed] ${JSON.stringify({
            failedChecks,
            request: {
                method: 'POST',
                url,
                headers: params.headers,
                body: payload,
            },
            response: {
                status: res && typeof res.status !== 'undefined' ? res.status : null,
                error: res && res.error ? res.error : null,
                error_code: res && typeof res.error_code !== 'undefined' ? res.error_code : null,
                timings: res && res.timings ? res.timings : null,
                headers: res && res.headers ? res.headers : null,
                body: res && typeof res.body === 'string'
                    ? res.body.slice(0, 1000)
                    : res && res.body
                        ? String(res.body).slice(0, 1000)
                        : null,
            },
        })}`
    );
}

// 2. 核心场景逻辑 (VU 执行的代码)
export default function () {
    // 动态生成测试数据，避免数据库缓存命中或唯一索引冲突
    const payload = JSON.stringify({
        title: `Task-${randomString(8)}`,
        description: `Load test task generated by k6 at ${new Date().toISOString()}`,
    });

    const url = `${BASE_URL}/tasks`;

    // 注入网关和后端的请求头
    const params = {
        headers: {
            'Content-Type': 'application/json',
            // 注入 Trace ID
            'X-Request-ID': `k6-perf-${randomString(10)}`,
        },
    };

    // 发起 POST 请求
    const res = http.post(url, payload, params);

    const checkResults = {
        'is status 202': res.status === 202,
        'has task id': safeJsonPath(res, 'task.id') !== undefined,
        'is status not 500': res.status !== 500,
    };

    check(res, checkResults);

    if (Object.values(checkResults).some((passed) => !passed)) {
        logFailure({ url, payload, params, res, checks: checkResults });
    }

    sleep(1);
}
